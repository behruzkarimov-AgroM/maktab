export const olympiadDict: Record<Locale, OlympiadStrings> = { uz, ru, en };

export const intlLocale: Record<Locale, string> = { uz: "uz-UZ", ru: "ru-RU", en: "en-GB" };

export function fmtDate(iso: string, locale: Locale, withTime = false): string {
  return withTime ? formatDateTime(locale, iso) : formatDate(locale, iso);
}

/** Month + year label (calendar header); uz via explicit month table. */
export function fmtMonthYear(locale: Locale, year: number, month0: number): string {
  if (locale === "uz") return `${UZ_MONTHS[month0]} ${year}`;
  return new Intl.DateTimeFormat(intlLocale[locale], { month: "long", year: "numeric", timeZone: "UTC" }).format(new Date(Date.UTC(year, month0, 1)));
}
